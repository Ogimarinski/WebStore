CREATE TABLE main_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sub_categories (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    main_category_id    BIGINT NOT NULL REFERENCES main_categories(id),
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE attributes (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    main_category_id        BIGINT REFERENCES main_categories(id),
    sub_category_id         BIGINT REFERENCES sub_categories(id),
    is_required             BOOLEAN NOT NULL DEFAULT FALSE,
    allows_multiple_values  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT attributes_exactly_one_owner
    CHECK (num_nonnulls(main_category_id, sub_category_id) = 1)
);

CREATE TABLE attribute_values (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id    BIGINT NOT NULL REFERENCES attributes(id),
    sort_order      SMALLINT NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE products (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sub_category_id     BIGINT NOT NULL REFERENCES sub_categories(id),
    price_net           NUMERIC(12, 2) NOT NULL CHECK (price_net >= 0), -- цена БЕЗ ДДС
    stock_quantity      INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    low_stock_threshold INTEGER NOT NULL DEFAULT 5 CHECK (low_stock_threshold >= 0),
    status              TEXT NOT NULL DEFAULT 'draft'
                        CHECK (status IN ('draft', 'published', 'inactive')),
    images              JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT products_images_shape
    CHECK (
        CASE WHEN jsonb_typeof(images) = 'array'
             THEN jsonb_array_length(images) <= 3
             ELSE FALSE
        END
    ),

    CONSTRAINT products_published_inactive_needs_three_images
    CHECK (
        status NOT IN ('published', 'inactive')
        OR CASE WHEN jsonb_typeof(images) = 'array'
                THEN jsonb_array_length(images) = 3
                ELSE FALSE
           END
    )
);

CREATE TABLE product_attribute_values (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT NOT NULL REFERENCES products(id),
    attribute_value_id  BIGINT NOT NULL REFERENCES attribute_values(id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT product_attribute_values_unique
        UNIQUE (product_id, attribute_value_id)
);

CREATE TABLE translations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type         TEXT NOT NULL REFERENCES translatable_entity_types(code),
    entity_id           BIGINT NOT NULL,
    locale              TEXT NOT NULL REFERENCES locales(code),
    name                TEXT NOT NULL,
    short_description   TEXT,
    long_description    TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT translations_unique_per_locale
        UNIQUE (entity_type, entity_id, locale)
);

CREATE VIEW main_category_translations AS
SELECT entity_id AS main_category_id, locale, name
FROM translations WHERE entity_type = 'main_category';

CREATE VIEW sub_category_translations AS
SELECT entity_id AS sub_category_id, locale, name
FROM translations WHERE entity_type = 'sub_category';

CREATE VIEW attribute_translations AS
SELECT entity_id AS attribute_id, locale, name
FROM translations WHERE entity_type = 'attribute';

CREATE VIEW attribute_value_translations AS
SELECT entity_id AS attribute_value_id, locale, name AS value
FROM translations WHERE entity_type = 'attribute_value';

CREATE VIEW product_translations AS
SELECT entity_id AS product_id, locale, name, short_description, long_description
FROM translations WHERE entity_type = 'product';

