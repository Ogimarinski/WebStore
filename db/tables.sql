CREATE TABLE orders (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id             BIGINT NOT NULL REFERENCES customers(id),

    status                  TEXT NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending', 'payment_processing', 'paid',
                                              'shipped', 'cancelled',
                                              'refund_processing', 'refunded')),

    shipping_full_name      TEXT NOT NULL,
    shipping_phone          TEXT NOT NULL,
    shipping_address        TEXT NOT NULL,
    shipping_city           TEXT NOT NULL,
    shipping_postcode       TEXT NOT NULL,
    shipping_country_code   TEXT NOT NULL REFERENCES countries(code),

    locale                  TEXT NOT NULL REFERENCES locales(code),
    currency_code           TEXT NOT NULL REFERENCES currencies(code),
    rate_per_base_snapshot  NUMERIC(12, 6) NOT NULL DEFAULT 1.000000
                            CHECK (rate_per_base_snapshot > 0),

    subtotal                NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    vat                     NUMERIC(12, 2) NOT NULL CHECK (vat >= 0),
    shipping_net                NUMERIC(12, 2) NOT NULL CHECK (shipping_net >= 0),
    shipping_vat            NUMERIC(12, 2) NOT NULL CHECK (shipping_vat >= 0),
    vat_rate                NUMERIC(5, 2) NOT NULL,
    total                   NUMERIC(12, 2) NOT NULL CHECK (total >= 0),

    expires_at              TIMESTAMPTZ NOT NULL,
    paid_at                 TIMESTAMPTZ,
    shipped_at              TIMESTAMPTZ,
    tracking_number         TEXT CHECK (btrim(tracking_number) <> ''),
    cancelled_at            TIMESTAMPTZ,
    cancellation_reason     TEXT CHECK (cancellation_reason IN
                                ('payment_expired', 'payment_declined')),

    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT orders_total_consistency
    CHECK (total = subtotal + vat + shipping_net + shipping_vat),

    CONSTRAINT orders_cancelled_consistency
    CHECK (
        (status = 'cancelled'
            AND cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL)
        OR
        (status <> 'cancelled'
            AND cancelled_at IS NULL AND cancellation_reason IS NULL)
    ),

    CONSTRAINT orders_paid_consistency
    CHECK (
        (status IN ('paid', 'shipped', 'refund_processing', 'refunded')
            AND paid_at IS NOT NULL)
        OR
        (status IN ('pending', 'payment_processing', 'cancelled')
            AND paid_at IS NULL)
    ),

    CONSTRAINT orders_shipped_consistency
    CHECK (
        (status = 'shipped' AND shipped_at IS NOT NULL)
        OR
        (status <> 'shipped' AND shipped_at IS NULL)
    ),

    CONSTRAINT orders_tracking_number_consistency
    CHECK (status = 'shipped' OR tracking_number IS NULL)
);

CREATE TABLE order_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT NOT NULL REFERENCES orders(id),
    product_id              BIGINT NOT NULL REFERENCES products(id),
    product_name_snapshot   TEXT NOT NULL,
    unit_price_net_snapshot NUMERIC(12, 2) NOT NULL CHECK (unit_price_net_snapshot >= 0),
    unit_vat                NUMERIC(12, 2) NOT NULL CHECK (unit_vat >= 0),
    quantity                INTEGER NOT NULL CHECK (quantity > 0),
    line_total              NUMERIC(12, 2) NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT order_items_line_total_consistency
    CHECK (line_total = (unit_price_net_snapshot + unit_vat) * quantity)
);

CREATE TABLE payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT NOT NULL REFERENCES orders(id),
    paypal_order_id     TEXT NOT NULL,
    paypal_capture_id   TEXT UNIQUE,
    status              TEXT NOT NULL DEFAULT 'processing'
                        CHECK (status IN ('processing', 'verifying', 'completed', 'failed')),
    raw_response        JSONB,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT payments_capture_id_consistency
    CHECK (status NOT IN ('verifying', 'completed') OR paypal_capture_id IS NOT NULL)
);

-- Искам order_id да е уникален само при тези статуси, constraint-ите нямат where
CREATE UNIQUE INDEX uq_payments_one_active_per_order
    ON payments(order_id)
    WHERE status IN ('processing', 'verifying', 'completed');

CREATE TABLE refunds (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT NOT NULL REFERENCES orders(id),
    admin_user_id       BIGINT NOT NULL REFERENCES admin_users(id),

    -- paypal: заявка към PayPal по capture ID-то на успешното плащане;
    -- manual: сумата е върната извън системата (напр. банков превод).
    method              TEXT NOT NULL CHECK (method IN ('paypal', 'manual')),

    -- processing: заявката е изпратена, няма окончателен отговор;
    -- completed / failed: крайни. Ръчното отбелязване е направо completed.
    status              TEXT NOT NULL DEFAULT 'processing'
                        CHECK (status IN ('processing', 'completed', 'failed')),

    paypal_refund_id    TEXT UNIQUE,
    failure_reason      TEXT,
    manual_note         TEXT CHECK (btrim(manual_note) <> ''),
    raw_response        JSONB,
    completed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT refunds_manual_consistency
    CHECK (
        (method = 'manual' AND status = 'completed'
            AND manual_note IS NOT NULL AND paypal_refund_id IS NULL)
        OR
        (method = 'paypal' AND manual_note IS NULL)
    ),
    CONSTRAINT refunds_paypal_completed_consistency
    CHECK (NOT (method = 'paypal' AND status = 'completed')
           OR paypal_refund_id IS NOT NULL),
    CONSTRAINT refunds_failed_consistency
    CHECK (
        (status = 'failed' AND failure_reason IS NOT NULL)
        OR
        (status <> 'failed' AND failure_reason IS NULL)
    ),
    CONSTRAINT refunds_completed_consistency
    CHECK (
        (status = 'completed' AND completed_at IS NOT NULL)
        OR
        (status <> 'completed' AND completed_at IS NULL)
    )
);

CREATE UNIQUE INDEX uq_refunds_one_active_per_order
    ON refunds(order_id)
    WHERE status IN ('processing', 'completed');

